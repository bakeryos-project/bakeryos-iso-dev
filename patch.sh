#!/usr/bin/env bash
#
# Patch a bakeryos-iso checkout for this variant.
#
#   patch.sh <src_dir>
#
# variant.conf, packages.remove and packages.add are read from this script's
# directory. The checkout is disposable: the upstream package list is only read,
# never edited, and the profiledef change is a small managed block.
set -euo pipefail

if (( $# < 1 )); then
    echo "usage: patch.sh <src_dir>" >&2
    exit 1
fi

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
src="$(cd -- "${1}" && pwd)"

# shellcheck source=variant.conf
source "${script_dir}/variant.conf"

: "${VARIANT:?VARIANT is missing from variant.conf}"
: "${PACKAGES_FILE:?PACKAGES_FILE is missing from variant.conf}"

base_packages="${src}/packages.x86_64"
out_packages="${src}/${PACKAGES_FILE}"
profiledef="${src}/profiledef.sh"

for file in "${base_packages}" "${profiledef}"; do
    if [[ ! -f "${file}" ]]; then
        echo "error: ${file} not found, is ${src} a bakeryos-iso checkout?" >&2
        exit 1
    fi
done

read_list() {
    [[ -f "${1}" ]] || return 0
    sed -e 's/#.*//' -e 's/[[:space:]]*$//' -e '/^[[:space:]]*$/d' "${1}"
}

mapfile -t base < <(read_list "${base_packages}")
mapfile -t dropped < <(read_list "${script_dir}/packages.remove")
mapfile -t added < <(read_list "${script_dir}/packages.add")

declare -A in_base=() drop=() seen=()
for pkg in "${base[@]}"; do
    in_base["${pkg}"]=1
done

for pkg in "${dropped[@]}"; do
    if [[ -z "${in_base[${pkg}]:-}" ]]; then
        echo "warning: '${pkg}' is listed in packages.remove but is not in packages.x86_64" >&2
    fi
    drop["${pkg}"]=1
done
for pkg in "${added[@]}"; do
    if [[ -n "${in_base[${pkg}]:-}" ]]; then
        echo "warning: '${pkg}' is listed in packages.add but is already in packages.x86_64" >&2
    fi
    if [[ -n "${drop[${pkg}]:-}" ]]; then
        echo "error: '${pkg}' is listed in both packages.add and packages.remove" >&2
        exit 1
    fi
done

result=()
for pkg in "${base[@]}"; do
    [[ -n "${drop[${pkg}]:-}" ]] && continue
    [[ -n "${seen[${pkg}]:-}" ]] && continue
    seen["${pkg}"]=1
    result+=("${pkg}")
done
for pkg in "${added[@]}"; do
    [[ -n "${seen[${pkg}]:-}" ]] && continue
    seen["${pkg}"]=1
    result+=("${pkg}")
done

{
    echo "# Generated by patch.sh from packages.x86_64. Do not edit by hand."
    echo "# Variant: ${VARIANT} (${#dropped[@]} removed, ${#added[@]} added)"
    echo
    printf '%s\n' "${result[@]}"
} >"${out_packages}"

cp -- "${script_dir}/variant.conf" "${src}/variant.conf"

begin_marker='# >>> bakeryos-variant (managed by patch.sh)'
end_marker='# <<< bakeryos-variant'

tmp="${profiledef}.patch"
awk -v begin="${begin_marker}" -v end="${end_marker}" '
    $0 == begin { skip = 1; next }
    $0 == end   { skip = 0; next }
    !skip
' "${profiledef}" >"${tmp}"

# Drop blank lines left behind by a previous block, then append a fresh one.
while [[ -s "${tmp}" ]] && [[ -z "$(tail -n 1 "${tmp}")" ]]; do
    sed -i '$d' "${tmp}"
done
{
    echo
    echo "${begin_marker}"
    echo '_variant_dir="$(dirname -- "${BASH_SOURCE[0]}")"'
    echo '. "${_variant_dir}/variant.conf"'
    echo 'packages="${_variant_dir}/${PACKAGES_FILE}"'
    echo 'unset _variant_dir'
    echo "${end_marker}"
} >>"${tmp}"
mv -- "${tmp}" "${profiledef}"

echo "patched ${VARIANT}: ${#result[@]} packages (${#dropped[@]} removed, ${#added[@]} added)"
